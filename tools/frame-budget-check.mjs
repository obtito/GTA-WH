import assert from 'node:assert/strict';
import { AdaptiveRenderScale } from '../js/frame-budget.js';
const run=(policy,fps,seconds)=>{for(let i=0;i<Math.ceil(fps*seconds);i++)policy.sample(1/fps);return policy.scale;};
const policy=new AdaptiveRenderScale(1.5);
assert.equal(run(policy,30,1),1.5,'A brief interaction spike does not change resolution');
assert(run(policy,30,3)<1.5,'Sustained slow frames reduce GPU pixel workload');
assert.equal(run(policy,20,30),.75,'Slow devices cannot fall below the minimum scale');
assert.equal(run(policy,60,4),.75,'A short fast period cannot immediately reverse downscaling');
assert.equal(run(policy,52,4),.75,'The stable middle band resets premature recovery');
assert(run(policy,60,16)>.75,'Sustained headroom restores detail');
assert(run(policy,120,250)<=1.5,'High-refresh screens cannot exceed device quality cap');
const lowDpr=new AdaptiveRenderScale(.6);
assert.equal(run(lowDpr,20,10),.6,'Never raise a low device cap to the normal quality floor');
const pause=new AdaptiveRenderScale(1.25);
run(pause,15,2);pause.reset();
assert.equal(run(pause,60,1),1.25,'Visibility resume starts a fresh timing window');
assert.equal(pause.sample(NaN),1.25);
assert.equal(pause.sample(0),1.25);
console.log('Frame budget checks passed: sustained load, hysteresis, bounds, high-refresh displays and resume reset.');
