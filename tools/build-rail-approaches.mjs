// Bake bank-side railway corridors against the same city and shoreline as the scene.
import { readFileSync, writeFileSync } from 'node:fs';
import { register } from 'node:module';
register('data:text/javascript,' + encodeURIComponent(`
  export async function resolve(s,c,n) {
    if(s==='three') return {url:${JSON.stringify(new URL('../vendor/three.module.js', import.meta.url).href)},shortCircuit:true};
    return n(s,c);
  }
`), import.meta.url);
const [{BRIDGES},{toV2},{CollisionGrid},{planLandRoads,roadFootprint},{terrainHeight}] = await Promise.all([
  import('../js/data.js'),import('../js/geo.js'),import('../js/collision.js'),import('../js/road-layout.js'),import('../js/world.js')
]);
const bytes=readFileSync(new URL('../data/city-collision.bin',import.meta.url));
const grid=new CollisionGrid(40);
grid.addRaw(new Float32Array(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength)));grid.build();
const blocked=poly=>grid.overlapsPolygon(poly,.18)||poly.some(p=>terrainHeight(...p)>1);
const {route}=planLandRoads([],blocked);
const [a,b]=BRIDGES[0].axis.map(p=>toV2(...p));
const L=Math.hypot(b[0]-a[0],b[1]-a[1]),dx=(b[0]-a[0])/L,dz=(b[1]-a[1])/L;
const mix=(a,b,t)=>a.map((v,i)=>v+(b[i]-v)*t);
const distance=(a,b)=>Math.hypot(a[0]-b[0],a[1]-b[1]);
const approaches=[];
for(const side of [0,1]) {
  const t=side===0?.15:.85,dir=side===0?-1:1;
  const at=(s,off=0)=>[a[0]+dx*(L*t+dir*s)-dz*off,a[1]+dz*(L*t+dir*s)+dx*off];
  const path=route(at(52),at(1100,side===0?-400:600),14.5);
  if(!path)throw new Error('No clear railway approach on bank '+side);
  const corners=[at(0),...path],points=[corners[0]];
  const append=p=>{if(distance(points.at(-1),p)>.001)points.push(p);};
  for(let i=1;i<corners.length-1;i++) {
    const prev=corners[i-1],p=corners[i],next=corners[i+1];
    let cut=Math.min(80,distance(prev,p)*.4,distance(p,next)*.4),curve;
    // Round every bend, shrinking only as much as the reserved corridor needs.
    for(let attempt=0;attempt<12;attempt++) {
      const enter=mix(p,prev,cut/distance(p,prev)),leave=mix(p,next,cut/distance(p,next));
      const n=Math.max(8,Math.ceil(cut/2));
      curve=Array.from({length:n+1},(_,j)=>{const u=j/n;return mix(mix(enter,p,u),mix(p,leave,u),u);});
      if(curve.every((q,j)=>!j||!blocked(roadFootprint(curve[j-1],q,16))))break;
      cut*=.65;
      if(attempt===11)throw new Error('Cannot round railway bend '+side+':'+i);
    }
    append(curve[0]);for(const p of curve.slice(1))append(p);
  }
  append(corners.at(-1));
  // Resample straight portions too: the renderer and grade checks share this mesh.
  const samples=[points[0]];
  for(let i=1;i<points.length;i++) {
    const n=Math.ceil(distance(points[i-1],points[i])/8);
    for(let j=1;j<=n;j++)samples.push(mix(points[i-1],points[i],j/n));
  }
  approaches.push({side,points:samples.map(p=>p.map(v=>+v.toFixed(5)))});
}
writeFileSync(new URL('../js/yangtze-rail-layout.js',import.meta.url),
  '// Generated by node tools/build-rail-approaches.mjs; scene corridors, not surveyed railway alignments.\n'+
  'export const YANGTZE_RAIL_APPROACHES = '+JSON.stringify(approaches)+';\n');
console.log('Railway approach corridors baked:',approaches.map(a=>({side:a.side,samples:a.points.length})));
